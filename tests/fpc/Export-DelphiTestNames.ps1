param(
    [Parameter(Mandatory = $true)][string]$Compiler,
    [Parameter(Mandatory = $true)][string]$DUnitXSource,
    [Parameter(Mandatory = $true)][string]$OutputRoot,
    [string]$Destination
)

$ErrorActionPreference = 'Stop'
# Use this host's Utility module even when PSModulePath includes another host.
Import-Module (Join-Path $PSHOME 'Modules\Microsoft.PowerShell.Utility\Microsoft.PowerShell.Utility.psd1') -ErrorAction Stop
$repository = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
if (-not $Destination) { $Destination = Join-Path $PSScriptRoot 'DelphiSharedTests.txt' }
$windowsPowerShell = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
$OutputRoot = & $windowsPowerShell -NoProfile -NonInteractive -File (Join-Path $PSScriptRoot 'Check-OutputPath.ps1') -Repository $repository -OutputPath $OutputRoot -CreateRun
if ($LASTEXITCODE -ne 0) { exit 2 }
Write-Output ('Delphi discovery output: ' + $OutputRoot)

# Read the explicit shared-unit roster, then let real DUnitX RTTI discover tests.
$runner = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'maxCronFpcTests.dpr'))
$units = @([regex]::Matches($runner, "(?m)^\s*(Test\w+) in '\.\.\\unit\\") |
    ForEach-Object { $_.Groups[1].Value } | Where-Object { $_ -ne 'TestZoneFakes' })
if ($units.Count -eq 0) { throw 'Empty shared-unit roster' }
$membership = @()
$registration = @()
$identities = @()
foreach ($unit in $units) {
    $path = Join-Path $repository "tests\unit\$unit.pas"
    $membership += "  $unit in '$path'"
    $fixtures = [regex]::Matches([IO.File]::ReadAllText($path), '(?i)\[TestFixture\]\s*(\w+)\s*=\s*class')
    if ($fixtures.Count -eq 0) { throw ('No fixture in ' + $path) }
    foreach ($fixture in $fixtures) { $registration += "  TDUnitX.RegisterTestFixture($unit.$($fixture.Groups[1].Value));" }
    $identities += '# SHA256 tests/unit/' + $unit + '.pas ' + (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
}
$source = @'
program DelphiTestNames;
{$APPTYPE CONSOLE}
uses System.SysUtils, DUnitX.TestFramework, DUnitX.Extensibility,
'@ + ($membership -join ",`r`n") + @'
;
procedure PrintFixture(const aFixture: ITestFixture);
var lTest: ITest; lChild: ITestFixture;
begin
  for lTest in aFixture.Tests do WriteLn(lTest.FullName);
  for lChild in aFixture.Children do PrintFixture(lChild);
end;
var lRunner: ITestRunner; lFixture: ITestFixture;
begin
  TDUnitX.CheckCommandLine;
'@ + ($registration -join "`r`n") + @'

  lRunner := TDUnitX.CreateRunner;
  lRunner.UseRTTI := True;
  for lFixture in (lRunner.BuildFixtures as ITestFixtureList) do PrintFixture(lFixture);
end.
'@
$sourcePath = Join-Path $OutputRoot 'DelphiTestNames.dpr'
[IO.File]::WriteAllText($sourcePath, (($source -replace '\r?\n', "`r`n") + "`r`n"))
$studio = Split-Path -Parent (Split-Path -Parent $Compiler)
$paths = @($repository, (Join-Path $repository 'tests\unit'), (Join-Path $repository 'lib\MaxLogicFoundation'),
    $DUnitXSource, (Join-Path $studio 'lib\win64\release')) -join ';'
$includePaths = @($repository, (Join-Path $repository 'lib\MaxLogicFoundation')) -join ';'
& $Compiler '-B' '-Q' '-DRELEASE;MAXCRON_TESTS;CONSOLE;NeverUninstall;NeverSleepOnMMThreadContention;UseSwitchToThread;UseReleaseStack' `
    '-NSSystem;Xml;Data;Winapi;System.Win' "-U$paths" "-I$includePaths" "-N0$OutputRoot" "-E$OutputRoot" $sourcePath `
    > (Join-Path $OutputRoot 'build.log') 2>&1
if ($LASTEXITCODE -ne 0) { exit 3 }
$names = @(& (Join-Path $OutputRoot 'DelphiTestNames.exe') | Where-Object { $_ -match '^Test\w+\.\w+\.' } | Sort-Object)
if ($LASTEXITCODE -ne 0 -or $names.Count -eq 0) { throw 'Delphi test discovery failed' }
# Refuse a raced source edit during compilation/discovery.
foreach ($identity in $identities) {
    $parts = $identity -split ' '
    if ((Get-FileHash -LiteralPath (Join-Path $repository $parts[2]) -Algorithm SHA256).Hash -ine $parts[3]) {
        throw ('Source changed during Delphi export: ' + $parts[2])
    }
}
[IO.File]::WriteAllLines($Destination, @('# Delphi DUnitX BuildFixtures, Windows x64; generated by Export-DelphiTestNames.ps1.') +
    @($identities | Sort-Object) + $names, [Text.UTF8Encoding]::new($true))
Write-Output ('Exported {0} Delphi test names to {1}' -f $names.Count, $Destination)
